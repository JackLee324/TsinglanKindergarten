/** 站规文本的指纹：规则改了 → 指纹变了 → 索引会重新生成（幂等且可追踪）。 */
export function siteRulesText(): string {
  return SITE_RULES.map((section) => `【${section.title}】\n${section.body}`).join('\n\n')
}

export function siteRulesSha256(): string {
  return createHash('sha256').update(siteRulesText(), 'utf8').digest('hex')
}
